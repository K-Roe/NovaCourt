import { test, expect, _electron as electron } from '@playwright/test'
import { mkdirSync, mkdtempSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

test('M3.1 real ConPTY terminals require Start and accept direct keyboard input', async () => {
  test.setTimeout(90_000)
  const cwd = resolve(fileURLToPath(new URL('..', import.meta.url)))
  const results = resolve(cwd, 'test-results')
  mkdirSync(results, { recursive: true })
  const userData = mkdtempSync(resolve(results, 'terminal-user-'))
  writeFileSync(resolve(userData, 'nova.json'), JSON.stringify({ endpoint: 'http://127.0.0.1:65534', workspace: cwd, sessionId: null, modelId: null }))
  const app = await electron.launch({ args: ['.'], cwd, env: { ...process.env, NC_V2_TEST: '1', NC_V2_ASTRA_FIXTURE: '1', NC_V2_USER_DATA: userData } })
  let finalPid: number | null = null
  try {
    await expect.poll(() => app.windows().find((candidate) => candidate.url().endsWith('/index.html'))?.url()).toContain('/index.html')
    const page = app.windows().find((candidate) => candidate.url().endsWith('/index.html'))!
    const errors: string[] = []
    page.on('pageerror', (error) => errors.push(error.message))
    page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()) })
    await page.getByRole('tab', { name: 'PowerShell' }).click()
    expect((await page.evaluate(() => window.novaCourt.getTerminalState())).status).toBe('idle')
    await page.getByRole('button', { name: 'Start', exact: true }).click()
    await expect.poll(async () => (await page.evaluate(() => window.novaCourt.getTerminalState())).status).toBe('running')
    const started = await page.evaluate(() => window.novaCourt.getTerminalState())
    expect(started.mode).toBe('powershell')
    expect(started.workspace?.toLowerCase()).toBe(cwd.toLowerCase())
    await page.locator('.xterm-helper-textarea').focus()
    await page.keyboard.type("Write-Output ('NOVA_PTY_OUTPUT_' + '8B2F')")
    await page.keyboard.press('Enter')
    await expect.poll(async () => (await page.evaluate(() => window.novaCourt.getTerminalState())).buffer, { timeout: 15_000 }).toContain('NOVA_PTY_OUTPUT_8B2F')
    await expect(page.locator('.court-terminal-screen')).toContainText('NOVA_PTY_OUTPUT_8B2F')
    await page.screenshot({ path: resolve(results, 'm31-powershell-terminal-renderer.png') })
    await page.getByRole('tab', { name: 'Nova Chat' }).click()
    expect((await page.evaluate(() => window.novaCourt.getTerminalState())).status).toBe('running')
    await page.getByRole('tab', { name: 'PowerShell' }).click()
    await expect(page.locator('.xterm-screen')).toBeVisible()
    await page.locator('.xterm-helper-textarea').focus()
    await page.keyboard.type('exit')
    await page.keyboard.press('Enter')
    await expect.poll(async () => (await page.evaluate(() => window.novaCourt.getTerminalState())).status).toBe('exited')

    await page.getByRole('tab', { name: 'OpenCode Terminal' }).click()
    expect((await page.evaluate(() => window.novaCourt.getTerminalState())).status).toBe('exited')
    await page.getByRole('button', { name: 'Start', exact: true }).click()
    await expect.poll(async () => (await page.evaluate(() => window.novaCourt.getTerminalState())).status).toBe('running')
    const opencode = await page.evaluate(() => window.novaCourt.getTerminalState())
    expect(opencode.mode).toBe('opencode')
    await expect.poll(async () => (await page.evaluate(() => window.novaCourt.getTerminalState())).buffer.length, { timeout: 15_000 }).toBeGreaterThan(100)
    const tuiBuffer = (await page.evaluate(() => window.novaCourt.getTerminalState())).buffer
    expect(tuiBuffer.includes('AssertionError')).toBe(false)
    expect(tuiBuffer.toLowerCase().includes('opencode')).toBe(true)
    await expect(page.locator('.court-terminal-screen')).toContainText('OpenCode')
    await page.waitForTimeout(1500)
    await page.screenshot({ path: resolve(results, 'm31-opencode-terminal-renderer.png') })
    const beforeModels = (await page.evaluate(() => window.novaCourt.getTerminalState())).buffer.length
    await page.locator('.xterm-helper-textarea').focus()
    await page.keyboard.type('/models')
    await page.keyboard.press('Enter')
    await expect.poll(async () => (await page.evaluate(() => window.novaCourt.getTerminalState())).buffer.length, { timeout: 10_000 }).toBeGreaterThan(beforeModels + 20)
    await page.screenshot({ path: resolve(results, 'm31-opencode-models-renderer.png') })
    const browserWindow = await app.browserWindow(page)
    const astra = await page.getByTestId('astra-viewport').boundingBox()
    const nova = await page.locator('.nova-panel').boundingBox()
    expect(astra!.x + astra!.width).toBeLessThan(nova!.x)
    await browserWindow.evaluate((window) => window.setSize(1120, 720))
    await expect.poll(async () => (await page.locator('.court-terminal-screen').boundingBox())!.width).toBeLessThan(nova!.width)
    await expect.poll(async () => (await page.evaluate(() => window.novaCourt.getTerminalState())).cols).toBeLessThan(opencode.cols!)
    const resizedCols = (await page.evaluate(() => window.novaCourt.getTerminalState())).cols!
    const divider = await page.getByRole('separator', { name: 'Resize Astra and Nova panels' }).boundingBox()
    await page.mouse.move(divider!.x + divider!.width / 2, divider!.y + divider!.height / 2)
    await page.mouse.down()
    await page.mouse.move(divider!.x - 50, divider!.y + divider!.height / 2, { steps: 6 })
    await page.mouse.up()
    await expect.poll(async () => (await page.evaluate(() => window.novaCourt.getTerminalState())).cols).toBeGreaterThan(resizedCols)
    await page.getByRole('button', { name: 'Settings', exact: true }).click()
    await expect.poll(async () => (await page.evaluate(() => window.novaCourt.getTerminalState())).status).toBe('running')
    await page.getByRole('button', { name: 'Conversation', exact: true }).click()
    await page.getByRole('tab', { name: 'OpenCode Terminal' }).click()
    await app.evaluate(({ dialog }) => { (dialog as any).showMessageBox = async () => ({ response: 0, checkboxChecked: false }) })
    await page.getByRole('button', { name: 'Stop', exact: true }).click()
    expect((await page.evaluate(() => window.novaCourt.getTerminalState())).status).toBe('running')
    await app.evaluate(({ dialog }) => { (dialog as any).showMessageBox = async () => ({ response: 1, checkboxChecked: false }) })
    await page.getByRole('button', { name: 'Stop', exact: true }).click()
    await expect.poll(async () => (await page.evaluate(() => window.novaCourt.getTerminalState())).status).toBe('exited')
    await page.getByRole('button', { name: 'Restart', exact: true }).click()
    await expect.poll(async () => (await page.evaluate(() => window.novaCourt.getTerminalState())).status).toBe('running')
    finalPid = (await page.evaluate(() => window.novaCourt.getTerminalState())).pid
    expect(errors).toEqual([])
  } finally { await app.close() }
  expect(finalPid).toBeTruthy()
  await expect.poll(() => { try { process.kill(finalPid!, 0); return true } catch { return false } }).toBe(false)
})
